    #[test]
    fn select_prefers_the_edid_then_cvt_in_range() {
        let e = asus();
        assert_eq!(select(&e, 1920, 1080, 60).unwrap().source, Source::Edid(0));
        assert_eq!(select(&e, 1920, 1080, 144).unwrap().source, Source::Edid(1));
        let m180 = select(&e, 1920, 1080, 180).unwrap();
        assert_eq!((m180.source, m180.clock_khz), (Source::Edid(3), 420_780));
        let m120 = select(&e, 1920, 1080, 120).unwrap();
        assert_eq!((m120.source, m120.clock_khz), (Source::Cvt, 274_560));
        assert_eq!(select(&e, 1920, 1080, 47), Err(ModeError::OutOfRange));
        assert_eq!(select(&e, 1920, 1080, 181), Err(ModeError::OutOfRange));
        // 2560x1440@144 is inside 48-180 Hz but needs 586 MHz > 430.
        assert_eq!(select(&e, 2560, 1440, 144), Err(ModeError::OutOfRange));
        assert_eq!(select(&e, 1280, 720, 100).unwrap().source, Source::Cvt);
    }

    /// 1080p180 fits the VPLL and a 4x HBR2 link, not the GOP's 2x HBR
    /// (what `/dev/dispctl mode` checks before touching anything).
    #[test]
    fn the_180_hz_modes_fit_vpll_and_4x_hbr2() {
        use crate::pll;
        use crate::supervisor::{dp_config, DpLink};
        let hbr2x4 = DpLink { bw: 0x14, nr: 4, ef: true, mst: false };
        for m in [select(&asus(), 1920, 1080, 180).unwrap(), cvt_rb2(1920, 1080, 180).unwrap()] {
            let c = pll::calc(&pll::tests::vpll(), m.clock_khz).unwrap();
            assert_eq!(c.p, 3, "{:?}", m);
            let hz = c.hz(27_000) as i64;
            assert!((hz - m.clock_khz as i64 * 1000).abs() < 2_000, "{} Hz for {} kHz", hz, m.clock_khz);
            let dp = dp_config(&m.timing(4), &hbr2x4).unwrap();
            assert!(dp.watermark > 6 && dp.watermark < 0x3f, "{:?}", dp);
            // 4 lanes x 5.4 Gb/s x 8/10 / 24 bpp = 720 MHz; 2x HBR = 180.
            assert!(m.clock_khz <= 4 * 0x14 * 27_000 * 8 / 24);
            assert!(m.clock_khz > 2 * 0x0a * 27_000 * 8 / 24);
        }
    }

