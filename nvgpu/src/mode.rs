    /// `edid-decode`'s "Hfront Hsync Hback Hpol / Vfront Vsync Vback Vpol"
    /// plus the clock in kHz.
    fn porches(m: &Mode) -> String {
        format!(
            "{}x{} {} kHz Hfront {} Hsync {} Hback {} Hpol {} Vfront {} Vsync {} Vback {} Vpol {}",
            m.hdisplay,
            m.vdisplay,
            m.clock_khz,
            m.hsync_start - m.hdisplay,
            m.hsync_end - m.hsync_start,
            m.htotal - m.hsync_end,
            if m.nhsync { 'N' } else { 'P' },
            m.vsync_start - m.vdisplay,
            m.vsync_end - m.vsync_start,
            m.vtotal - m.vsync_end,
            if m.nvsync { 'N' } else { 'P' },
        )
    }

    /// `edid-decode --cvt w=W,h=H,fps=F,rb=2` (1.32.0), transcribed.
    #[test]
    fn cvt_rb2_matches_edid_decode() {
        let cases: &[(u16, u16, u32, &str)] = &[
            (1920, 1080, 60, "1920x1080 133320 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 17 Vsync 8 Vback 6 Vpol N"),
            (1920, 1080, 120, "1920x1080 274560 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 50 Vsync 8 Vback 6 Vpol N"),
            (1920, 1080, 144, "1920x1080 333216 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 63 Vsync 8 Vback 6 Vpol N"),
            (1920, 1080, 165, "1920x1080 385770 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 75 Vsync 8 Vback 6 Vpol N"),
            (1920, 1080, 180, "1920x1080 424080 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 84 Vsync 8 Vback 6 Vpol N"),
            (1920, 1080, 48, "1920x1080 106080 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 11 Vsync 8 Vback 6 Vpol N"),
            // edid-decode: 110.599 MHz (its float floor; see `cvt_rb2`).
            (1920, 1080, 50, "1920x1080 110600 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 12 Vsync 8 Vback 6 Vpol N"),
            (2560, 1440, 144, "2560x1440 586586 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 89 Vsync 8 Vback 6 Vpol N"),
            (1280, 720, 60, "1280x720 60465 kHz Hfront 8 Hsync 32 Hback 40 Hpol P Vfront 7 Vsync 8 Vback 6 Vpol N"),
        ];
        for &(w, h, hz, want) in cases {
            let m = cvt_rb2(w, h, hz).unwrap();
            assert_eq!(porches(&m), want, "{}x{}@{}", w, h, hz);
            assert_eq!(m.source, Source::Cvt);
        }
        assert_eq!(cvt_rb2(1920, 1080, 180).unwrap().refresh_mhz(), 180_000);
        // 1280x720@60 floors its clock: edid-decode says 59.999405 Hz.
        assert_eq!(cvt_rb2(1280, 720, 60).unwrap().refresh_mhz(), 59_999);
        assert_eq!(cvt_rb2(1920, 1080, 0), None);
        assert_eq!(cvt_rb2(1920, 1080, 2174), None, "460 us of blanking leaves no active time");
    }

